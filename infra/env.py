"""Environment management — ~/.agi/env is the only source of truth."""
from __future__ import annotations
import os, re
from pathlib import Path

ENV_FILE = Path.home() / ".agi" / "env"

REQUIRED = {
    "AGI_BASE_URL": "https://<tunnel>.trycloudflare.com/v1",
    "AGI_MODEL": "gpt-oss-20b",
    "AGI_PROVIDER": "colab",
    "AGI_PROVIDER_KIND": "openai_compat",
    "AGI_API_KEY": "local",
    "AGI_TOOLS_FAMILIES": "1",
    "AGI_PROVIDER_TIMEOUT_S": "600",
}


def load_env(required: bool = False) -> dict[str, str]:
    """Load ~/.agi/env into os.environ. Returns what was loaded."""
    if not ENV_FILE.exists():
        if required:
            raise SystemExit(f"FATAL: {ENV_FILE} missing. Run scripts/infra_up first.")
        return {}
    loaded: dict[str, str] = {}
    for line in ENV_FILE.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r'(?:export\s+)?([A-Z_][A-Z0-9_]*)=(.*)', line)
        if not m:
            continue
        k, v = m.group(1), m.group(2).strip()
        if (v.startswith('"') and v.endswith('"')) or (v.startswith("'") and v.endswith("'")):
            v = v[1:-1]
        os.environ[k] = v
        loaded[k] = v
    return loaded


def save_env(values: dict[str, str]) -> None:
    """Write ~/.agi/env atomically. Merges into existing."""
    ENV_FILE.parent.mkdir(parents=True, exist_ok=True)
    current: dict[str, str] = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text().splitlines():
            m = re.match(r'(?:export\s+)?([A-Z_][A-Z0-9_]*)=(.*)', line.strip())
            if m and not line.strip().startswith("#"):
                current[m.group(1)] = m.group(2)
    current.update(values)
    lines = ["# Generated by infra/env.py — edit via scripts/infra_up", ""]
    for k, v in sorted(current.items()):
        lines.append(f'export {k}="{v}"')
    tmp = ENV_FILE.with_suffix(".tmp")
    tmp.write_text("\n".join(lines) + "\n")
    tmp.replace(ENV_FILE)
    os.chmod(ENV_FILE, 0o600)


def env_snapshot() -> dict:
    """Return current env for provenance (no keys)."""
    keys = ["AGI_BASE_URL", "AGI_MODEL", "AGI_PROVIDER", "AGI_PROVIDER_KIND"]
    return {k: os.environ.get(k, "") for k in keys}
