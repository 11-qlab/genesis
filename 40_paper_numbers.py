#!/usr/bin/env python3
"""40_paper_numbers.py — emit paste-ready numbers.md.

Sources: taxonomy.json (evidence.affected_models, tightened, held_out_tests),
         results/H*.json (hypothesis verdicts already validated),
         state/anchor_verdicts.jsonl (ground-truth proof),
         state/anomalies.jsonl (unexplained failures).
Writes: paper/numbers.md
Exit:   1 if any class lacks cross-family evidence.
"""
import json, sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUTD = ROOT / "paper"; OUTD.mkdir(exist_ok=True)
OUT  = OUTD / "numbers.md"

tax    = json.loads((ROOT / "taxonomy.json").read_text())
jrn    = [json.loads(l) for l in (ROOT / "autonomous_journal.jsonl").read_text().splitlines() if l.strip()]
verd   = [json.loads(l) for l in (ROOT / "state/anchor_verdicts.jsonl").read_text().splitlines() if l.strip()] \
         if (ROOT / "state/anchor_verdicts.jsonl").exists() else []
anoms  = [json.loads(l) for l in (ROOT / "state/anomalies.jsonl").read_text().splitlines() if l.strip()] \
         if (ROOT / "state/anomalies.jsonl").exists() else []
H      = [json.loads(p.read_text()) for p in sorted((ROOT / "results").glob("H*.json"))]

classes = tax.get("classes", [])
models  = sorted({m for c in classes for m in c.get("evidence", {}).get("affected_models", {})})
meas    = tax.get("measurement", {})
conc    = tax.get("conclusion", {})
fis     = tax.get("finding_inverse_scaling", {})
hyp     = tax.get("hypothesis_confirmed", [])

def sym(v): return "" if v is None else f"{v:.3f}"

L = []
L.append("# Paper numbers — auto-generated by 40_paper_numbers.py\n")
L.append(f"**taxonomy version:** {tax.get('version','?')}  ")
L.append(f"**generated:** {tax.get('generated','?')}  ")
L.append(f"**total_calls:** {meas.get('total_calls','?')}  ")
L.append(f"**valid_calls:** {meas.get('valid_calls','?')}  ")
L.append(f"**infra_artifacts:** {meas.get('infra_artifacts','?')}  ")

L.append("\n## Cross-family pass rate per class\n")
L.append("| class | " + " | ".join(models) + " | subtype | mechanism (trunc) |")
L.append("|---|" + "---|" * len(models) + "---|---|")
cross_family_classes = []
for c in classes:
    key = c["name"] + "/" + c["subtype"]
    ev  = c.get("evidence", {})
    am  = ev.get("affected_models", {})
    if len(am) >= 2: cross_family_classes.append(key)
    cells = []
    for m in models:
        s = am.get(m)
        cells.append(f"{s.get('n_passed',0)}/{s.get('n_valid',0)} ({sym(s.get('pass_valid'))})" if s else "—")
    L.append(f"| `{key}` | " + " | ".join(cells) + f" | {c.get('subtype','')} | {c.get('mechanism','')[:60]}… |")

L.append("\n## Tightened intervention (recipe stated, no example)\n")
L.append("| class | n | n_passed | pass_valid | pass_all | source |")
L.append("|---|---|---|---|---|---|")
for c in classes:
    t = c.get("evidence", {}).get("tightened") or {}
    if not t: continue
    key = c["name"] + "/" + c["subtype"]
    L.append(f"| `{key}` | {t.get('n','?')} | {t.get('n_passed','?')} | "
             f"{sym(t.get('pass_valid'))} | {sym(t.get('pass_all'))} | {t.get('source','—')} |")

L.append("\n## Ground-truth anchor verification\n")
if verd:
    per_cls = Counter(v["class"] for v in verd if v["verdict"] == "DISCRIMINATES")
    tot_cls = Counter(v["class"] for v in verd)
    L.append("| class | anchors | discriminating | grounded |")
    L.append("|---|---|---|---|")
    for cls in sorted(tot_cls):
        d, t = per_cls[cls], tot_cls[cls]
        L.append(f"| `{cls}` | {t} | {d} | {'✓' if d>0 else '✗'} |")
    L.append(f"\n**Classes grounded: {len(per_cls)}/{len(tot_cls)}** "
             f"(a class is grounded iff ≥1 template discriminates known-correct from baseline)")
else:
    L.append("_(run ./20_verify_anchors.py first)_")

L.append("\n## Existing validated hypotheses (results/H*.json)\n")
L.append("| id | n_pairs | agree | verdict |")
L.append("|---|---|---|---|")
for h in H:
    if "verdict" not in h: continue
    L.append(f"| {h.get('id','?')} | {h.get('n_pairs','—')} | {h.get('agree','—')} | {h.get('verdict','—')} |")

L.append("\n## Anomalies (unexplained failures)\n")
if anoms:
    c = Counter(a["kind"] for a in anoms)
    L.append("| kind | count |")
    L.append("|---|---|")
    for k, n in c.most_common(): L.append(f"| {k} | {n} |")
else:
    L.append("_(none surfaced)_")

L.append("\n## Findings (verbatim from taxonomy.json)\n")
if conc.get("statement"): L.append(f"**Conclusion:** {conc['statement']}\n")
if fis.get("statement"):  L.append(f"**Inverse scaling:** {fis['statement']}\n")
if hyp:
    L.append("**Confirmed hypotheses:**")
    for h in hyp: L.append(f"- {h}")

OUT.write_text("\n".join(L) + "\n")
print(f"wrote {OUT}")

missing = [c["name"] + "/" + c["subtype"] for c in classes
           if len(c.get("evidence", {}).get("affected_models", {})) < 2]
if missing:
    print(f"\n[WARN] classes lacking cross-family confirmation: {missing}")
    sys.exit(1)
print(f"[ OK ] all {len(classes)} classes cross-family confirmed.")
